async page => {
  const report = [], errors = []
  await page.unrouteAll()
  page.on('pageerror', error => errors.push(error.message))
  const check = (condition, message) => { if (!condition) throw Error(message) }
  const target = 'http://127.0.0.1:54831', source = 'http://127.0.0.1:54830'
  const shots = 'output/playwright/unified-ui-fixed-20261111/'
  await page.setViewportSize({width:1280,height:1000})
  await page.goto(target)
  await page.getByRole('heading',{name:'从第一条片刻开始',exact:true}).waitFor()
  await page.getByRole('button',{name:'设置',exact:true}).click()
  const settings = page.getByRole('dialog',{name:'AuraCap 设置',exact:true})
  await settings.waitFor()
  check(await settings.locator('.ac-memory-section,.ac-usage-section,.ac-backup-section').count()===3,'Disconnected settings must show all local sections')
  await settings.getByRole('button',{name:'编辑项目上下文'}).click()
  await settings.locator('textarea').fill('保留本次编辑草稿')
  await settings.getByRole('button',{name:'把手机接进来',exact:true}).click()
  await settings.getByRole('button',{name:'从备份恢复',exact:true}).click()
  await page.getByRole('dialog',{name:'从备份恢复',exact:true}).waitFor()
  check(await page.locator('.ac-modal[inert]').count()===1,'The underlying settings must be inert')
  await page.keyboard.press('Escape')
  await settings.waitFor()
  check(await settings.locator('textarea').inputValue()==='保留本次编辑草稿','Opening and closing restore lost the draft')
  check(await settings.getByRole('button',{name:'把手机接进来',exact:true}).getAttribute('aria-expanded')==='true','Opening restore reset expansion state')
  await settings.getByRole('button',{name:'导出',exact:true}).click()
  const menu = page.getByRole('menu',{name:'选择导出内容'})
  await menu.waitFor()
  check(await menu.getByRole('menuitem').count()===3,'Export menu must contain exactly three modes')
  await page.keyboard.press('ArrowDown')
  check((await page.evaluate(()=>document.activeElement.textContent)).includes('仅导出图片'),'Arrow navigation did not move to images')
  await page.keyboard.press('Escape')
  check(await settings.isVisible(),'Menu Escape closed settings')
  await page.keyboard.press('/')
  check(await page.locator('.ac-search-panel').count()===0,'Global search opened inside the modal')
  await page.screenshot({path:shots+'local-settings.png'})
  await page.keyboard.press('Escape')
  check(await settings.count()===0,'Settings Escape did not close settings')
  report.push('Disconnected local sections, modal focus hierarchy, draft and expansion retention, menu keys')

  const flowResponse = page.waitForResponse(response=>response.url().endsWith('/github/device')&&response.request().method()==='POST')
  await page.getByRole('button',{name:'连接手机',exact:true}).click()
  const flow = await (await flowResponse).json()
  await page.getByRole('heading',{name:'连接 GitHub 中转',exact:true}).waitFor()
  check(await page.evaluate(()=>document.activeElement.matches('[data-stage-title]')),'A task transition must focus the new heading')
  await page.getByRole('button',{name:'返回',exact:true}).click()
  await page.getByRole('heading',{name:'从第一条片刻开始',exact:true}).waitFor()
  check((await (await page.request.get(target+'/auracap/api/github/device/'+flow.id)).json()).status==='cancelled','Back did not cancel the server authorization')
  await page.getByRole('button',{name:'从备份恢复',exact:true}).click()
  await page.getByRole('dialog',{name:'从备份恢复',exact:true}).waitFor()
  check(await page.locator('.ac-settings').count()===0,'Welcome restore incorrectly requires opening settings')
  await page.keyboard.press('Escape')
  report.push('Real authorization cancellation, heading focus, direct welcome restore')

  await page.goto(source)
  const sourceNote=(await (await page.request.get(source+'/auracap/api/memory/profile')).json()).note
  await page.getByRole('button',{name:'双栏',exact:true}).click()
  await page.getByRole('heading',{name:'设计记录',exact:true}).waitFor()
  await page.getByRole('button',{name:'卡片',exact:true}).click()
  await page.locator('.ac-card').first().waitFor()
  await page.screenshot({path:shots+'cards.png'})
  await page.getByRole('button',{name:'设置',exact:true}).click()
  const sourceSettings=page.getByRole('dialog',{name:'AuraCap 设置',exact:true})
  await sourceSettings.getByRole('button',{name:'导出',exact:true}).click()
  const downloading=page.waitForEvent('download')
  await page.getByRole('menuitem',{name:/导出整个包/}).click()
  const download=await downloading
  const backupFile=shots+'roundtrip.auracap.zip'
  await download.saveAs(backupFile)
  report.push('Actual full-package export from the new settings')

  await page.goto(target)
  await page.getByRole('heading',{name:'从第一条片刻开始',exact:true}).waitFor()
  await page.getByRole('button',{name:'从备份恢复',exact:true}).click()
  await page.locator('input[type="file"][accept=".zip,application/zip"]').setInputFiles(backupFile)
  const restore=page.getByRole('dialog',{name:'从备份恢复',exact:true})
  await restore.getByRole('button',{name:'恢复此备份',exact:true}).waitFor()
  check(await restore.locator('.bk-summary b').allTextContents().then(values=>values.join(',')==='3,2,4'),'Restore counts differ from the real package')
  await restore.getByRole('button',{name:'重新选择',exact:true}).click()
  await restore.getByRole('button',{name:'选择备份文件 .auracap.zip'}).waitFor()
  check(await page.evaluate(()=>Boolean(document.activeElement.closest('.bk-restore-card'))),'Choosing another file lost modal focus')
  await page.locator('input[type="file"][accept=".zip,application/zip"]').setInputFiles(backupFile)
  await restore.getByRole('button',{name:'恢复此备份',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'设置',exact:true}).click()
  const targetSettings=page.getByRole('dialog',{name:'AuraCap 设置',exact:true})
  await targetSettings.getByRole('button',{name:'编辑项目上下文'}).click()
  await targetSettings.locator('textarea').fill('这是旧库草稿，恢复后必须失效')
  await targetSettings.getByRole('button',{name:'从备份恢复',exact:true}).click()
  await restore.getByRole('button',{name:'恢复此备份',exact:true}).waitFor()
  await page.screenshot({path:shots+'restore-confirm.png'})
  await restore.getByRole('button',{name:'恢复此备份',exact:true}).click()
  const completed=page.getByRole('dialog',{name:'恢复完成',exact:true})
  await completed.waitFor()
  await page.screenshot({path:shots+'restore-complete.png'})
  await completed.getByRole('button',{name:'完成',exact:true}).click()
  await targetSettings.getByRole('button',{name:'编辑项目上下文'}).click()
  await targetSettings.locator('textarea').waitFor()
  await page.waitForFunction(note=>document.querySelector('.ac-settings textarea')?.value===note,sourceNote)
  check(await targetSettings.locator('textarea').inputValue()!=='这是旧库草稿，恢复后必须失效','A pre-restore draft survived the library replacement')
  const profile=await (await page.request.get(target+'/auracap/api/memory/profile')).json()
  const usage=await (await page.request.get(target+'/auracap/api/usage')).json()
  check(profile.note===sourceNote&&usage.total===0,'Restored profile or reset usage is incorrect')
  report.push('Welcome upload reuses settings confirmation; restore survives remount and discards old drafts')

  await page.route('**/auracap/api/items?view=list*',async route=>{
    const response=await route.fetch(),data=await response.json()
    await route.fulfill({response,json:{...data,items:[],groups:[],version:'report-only'}})
  })
  await page.route('**/auracap/api/insights/status',async route=>{
    const response=await route.fetch(),data=await response.json()
    await route.fulfill({response,json:{day:null,week:null,month:null,year:data.year}})
  })
  await page.reload()
  await page.getByRole('heading',{name:'year 已有结果',exact:true}).waitFor()
  check(await page.getByRole('heading',{name:'从第一条片刻开始',exact:true}).count()===0,'A report-only library was hidden behind onboarding')
  report.push('Report-only library opens the saved year report without generating it')
  check(errors.length===0,'Browser runtime errors: '+errors.join('; '))
  await page.evaluate(value=>{window.__uiCheck=value},{passed:report,runtimeErrors:errors})
}
