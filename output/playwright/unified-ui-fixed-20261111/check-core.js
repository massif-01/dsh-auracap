async page => {
  const out = 'output/playwright/unified-ui-fixed-20261111/'
  const passed = [], runtimeErrors = [], measurements = {}
  page.on('pageerror', error => runtimeErrors.push(error.message))
  page.setDefaultTimeout(8000)
  await page.setViewportSize({ width: 1280, height: 1000 })
  const origin = new URL(page.url()).origin
  await page.unrouteAll()
  await page.evaluate(() => { localStorage.removeItem('auracap.backupTask'); localStorage.removeItem('auracap.shortcutDownloadedRepo'); localStorage.setItem('auracap.view', 'split') })
  const check = (value, message) => { if (!value) throw Error(message) }
  const wait = async fn => { for (let i = 0; i < 150; i++) { if (await fn()) return; await page.waitForTimeout(30) } throw Error('Expected state did not arrive') }
  const settings = page.getByRole('dialog', { name: 'AuraCap 设置', exact: true })

  let releaseProfile
  await page.route('**/auracap/api/memory/profile', async route => {
    await new Promise(resolve => { releaseProfile = resolve })
    const response = await route.fetch(); await route.fulfill({ response })
  })
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await settings.getByText('正在载入项目上下文…', { exact: true }).waitFor()
  check(await settings.locator('textarea').count() === 0, 'Unloaded profile must not create an editable empty draft')
  releaseProfile()
  await settings.locator('.ac-project-read-note').waitFor()
  await page.unroute('**/auracap/api/memory/profile')
  await page.screenshot({ path: out + 'settings-read.png' })
  await settings.getByRole('button', { name: '编辑项目上下文', exact: true }).click()
  await settings.locator('textarea').fill('正在整理 AuraCap 的界面，让截图、文档与洞察能自然地串联起来。')
  measurements.actions = await settings.locator('.ac-project-actions').evaluate(element => {
    const [a, b] = element.querySelectorAll('button'), x = a.getBoundingClientRect(), y = b.getBoundingClientRect()
    return { gap: y.left - x.right, primaryHeight: x.height, secondaryHeight: y.height, labelColor: getComputedStyle(document.querySelector('.ac-settings-subsection')).color }
  })
  check(measurements.actions.gap >= 10 && measurements.actions.secondaryHeight >= 28, 'Actions are too close or have an undersized target')
  await settings.locator('.ac-project-actions').screenshot({ path: out + 'save-cancel.png' })
  await settings.getByRole('button', { name: '从备份恢复', exact: true }).click()
  await page.getByRole('dialog', { name: '从备份恢复', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  check((await settings.locator('textarea').inputValue()).includes('正在整理 AuraCap'), 'Restore open/close lost the draft')
  let failSave
  await page.route('**/auracap/api/memory/profile', async route => {
    if (route.request().method() !== 'PUT') return route.continue()
    await new Promise(resolve => { failSave = resolve })
    await route.fulfill({ status: 500, json: { error: '测试：保存失败，草稿已保留' } })
  })
  await settings.getByRole('button', { name: '保存上下文', exact: true }).click()
  await settings.getByRole('button', { name: '保存中…', exact: true }).waitFor()
  await wait(() => page.evaluate(() => Boolean(document.activeElement.closest('.ac-settings'))))
  failSave()
  await settings.getByRole('alert').getByText('测试：保存失败，草稿已保留', { exact: true }).waitFor()
  check(await page.locator('.ac-banner').count() === 0, 'Settings error leaked behind the modal')
  await page.screenshot({ path: out + 'settings-save-failed.png' })
  await page.unroute('**/auracap/api/memory/profile')
  await settings.getByRole('button', { name: '保存上下文', exact: true }).click()
  await settings.locator('.ac-project-read-note').getByText(/正在整理 AuraCap/).waitFor()
  await page.screenshot({ path: out + 'settings-saved-context.png' })
  await page.keyboard.press('Escape')
  check(await settings.count() === 0, 'Settings Escape stopped working after an async save')
  check(await page.getByRole('button', { name: '设置', exact: true }).evaluate(element => element === document.activeElement), 'Settings did not return focus to its original entry')
  passed.push('Profile waits for data; draft and errors stay local; save/cancel spacing, saved content and nested focus verified')

  const task = await (await page.request.post(origin + '/auracap/api/backup/tasks', { data: { type: 'restore', operationId: crypto.randomUUID() } })).json()
  await page.evaluate(id => localStorage.setItem('auracap.backupTask', JSON.stringify({ id, type: 'export', downloadRequested: true })), crypto.randomUUID())
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await wait(() => page.evaluate(id => JSON.parse(localStorage.getItem('auracap.backupTask'))?.id === id, task.id))
  check(await settings.getByRole('button', { name: '导出', exact: true }).isDisabled(), 'The actual active task was not adopted')
  await settings.locator('.bk-notice').getByRole('button', { name: '取消', exact: true }).click()
  await wait(async () => !(await (await page.request.get(origin + '/auracap/api/backup/status')).json()).active)
  await settings.getByRole('button', { name: '关闭', exact: true }).click()
  passed.push('Server activity replaces a stale local task and can be cancelled from the UI')

  const expiredStatus = async route => {
    const response = await route.fetch(), data = await response.json()
    await route.fulfill({ response, json: { ...data, needsReconnect: true, reconnectReason: 'token_invalid', lastError: 'GitHub token 已失效，请重新连接' } })
  }
  await page.route('**/auracap/api/github/status', expiredStatus)
  await page.route('**/auracap/api/github/sync*', expiredStatus)
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  check(await settings.getByText('授权长期有效，不需要定期重新登录。', { exact: true }).count() === 0, 'Expired authorization still says it is valid')
  await settings.getByRole('button', { name: '重新连接 GitHub', exact: true }).click()
  await settings.getByRole('button', { name: '返回', exact: true }).waitFor()
  check(await settings.getByRole('button', { name: '重新连接 GitHub', exact: true }).isDisabled(), 'An active connection can be restarted from the same UI')
  measurements.authorization = await settings.locator('.ac-device .ac-action-row').evaluate(element => { const [a, b] = element.children; return { gap: b.getBoundingClientRect().left - a.getBoundingClientRect().right } })
  await settings.locator('.ac-device').screenshot({ path: out + 'authorization-actions.png' })
  await page.reload()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await settings.getByRole('button', { name: '返回', exact: true }).waitFor()
  await settings.getByRole('button', { name: '返回', exact: true }).click()
  await settings.locator('.ac-device').waitFor({ state: 'detached' })
  check((await (await page.request.get(origin + '/auracap/api/github/status')).json()).device === null, 'Return left an invisible active authorization')
  await page.unrouteAll()
  await settings.getByRole('button', { name: '关闭', exact: true }).click()
  passed.push('One phone flow survives reload, returns cleanly, and has honest status and separated actions')

  await page.getByRole('button', { name: '卡片', exact: true }).click()
  await page.locator('.ac-group-card').click()
  const groupDialog = page.locator('.ac-modal-card[role="dialog"]')
  await groupDialog.waitFor()
  await page.keyboard.press('/')
  check(await page.locator('.ac-search-panel').count() === 0, 'Search opened above the group dialog')
  measurements.groupSurface = await groupDialog.evaluate(element => ({ radius: getComputedStyle(element).borderRadius, shadow: getComputedStyle(element).boxShadow }))
  await page.screenshot({ path: out + 'group-dialog.png' })
  await page.keyboard.press('Escape')
  check(await groupDialog.count() === 0, 'Group Escape did not close the dialog')
  await page.getByRole('button', { name: '双栏', exact: true }).click()
  await page.getByRole('button', { name: 'AuraCap', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.ac-entity-name')?.textContent === 'AuraCap')
  await page.screenshot({ path: out + 'entity-dialog.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '查看原图', exact: true }).click()
  await page.getByRole('dialog', { name: '查看原图', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  check(await page.locator('.ac-lightbox').count() === 0, 'Image dialog Escape failed')
  passed.push('Group, entity and image dialogs use shared focus and surface rules; background shortcuts stay blocked')

  await page.route('**/auracap/api/items?view=list*', async route => {
    const response = await route.fetch(), data = await response.json()
    await route.fulfill({ response, json: { ...data, items: [], groups: [], version: 'empty-ui-regression' } })
  })
  let insightFails = true
  await page.route('**/auracap/api/insights/status', route => route.fulfill(insightFails ? { status: 503, json: { error: '测试：洞察状态暂不可用' } } : { json: {} }))
  await page.route('**/auracap/api/github/status', route => route.fulfill({ json: { connected: false, device: null } }))
  await page.route('**/auracap/api/github/sync*', route => route.fulfill({ json: { connected: false, device: null } }))
  await page.reload()
  await page.getByRole('heading', { name: '暂时无法载入内容', exact: true }).waitFor()
  check(await page.getByRole('button', { name: '从电脑导入', exact: true }).isEnabled(), 'Import is unavailable after a read failure')
  await page.getByRole('button', { name: '从备份恢复', exact: true }).click()
  await page.getByRole('dialog', { name: '从备份恢复', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: out + 'library-read-failed.png' })
  insightFails = false
  await page.getByRole('button', { name: '重新载入', exact: true }).click()
  await page.getByRole('heading', { name: '从第一条片刻开始', exact: true }).waitFor()
  passed.push('An initial insight-read failure ends loading, keeps local actions available, and retries into the welcome page')

  await page.unroute('**/auracap/api/github/status')
  await page.unroute('**/auracap/api/github/sync*')
  let failDownload = false
  await page.route('**/auracap/api/github/shortcut-file', route => route.fulfill(failDownload ? { status: 503, json: { error: '测试：下载暂不可用' } } : { contentType: 'application/octet-stream', body: 'isolated-fixture-shortcut' }))
  await page.reload()
  await page.getByRole('button', { name: '下载快捷指令', exact: true }).click()
  await page.getByRole('heading', { name: '等待第一张图片', exact: true }).waitFor()
  failDownload = true
  await page.getByRole('button', { name: '重新下载', exact: true }).click()
  await page.getByRole('alert').getByText('测试：下载暂不可用', { exact: true }).waitFor()
  check(await page.getByRole('heading', { name: '等待第一张图片', exact: true }).count() === 1, 'A failed re-download reset the stage')
  await page.reload()
  await page.getByRole('heading', { name: '等待第一张图片', exact: true }).waitFor()
  await page.screenshot({ path: out + 'waiting-after-reload.png' })
  passed.push('Download progress is independent from the last request and persists honestly across reloads')
  await page.unrouteAll()
  await page.reload()
  check(runtimeErrors.length === 0, runtimeErrors.join('\n'))
  await page.evaluate(result => { window.__fixedCore = result }, { passed, measurements, runtimeErrors })
}
